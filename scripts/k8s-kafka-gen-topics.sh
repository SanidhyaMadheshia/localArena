#!/usr/bin/env bash
# Regenerate infra/kafka/base/topics.yaml (KafkaTopic CRs) from the topic table in
# scripts/kafka-topics.sh, so the compose and Strimzi topic sets cannot drift.
# RF is 3 for every topic. Usage: scripts/k8s-kafka-gen-topics.sh
set -euo pipefail
cd "$(dirname "$0")/.."
out=infra/kafka/base/topics.yaml
{
  echo "# GENERATED by scripts/k8s-kafka-gen-topics.sh from scripts/kafka-topics.sh. Do not edit by hand."
  grep -E '^  "game\.' scripts/kafka-topics.sh | tr -d '"' | while read -r name parts cfg _key; do
    echo "---"
    echo "apiVersion: kafka.strimzi.io/v1"
    echo "kind: KafkaTopic"
    echo "metadata:"
    echo "  name: ${name//./-}"
    echo "  labels: { strimzi.io/cluster: localarena }"
    echo "spec:"
    echo "  topicName: $name   # key: $_key"
    echo "  partitions: $parts"
    echo "  replicas: 3"
    echo "  config:"
    IFS=, read -ra kv <<<"$cfg"
    for c in "${kv[@]}"; do
      k=${c%%=*}; v=${c#*=}
      echo "    $k: $v"
    done
  done
} > "$out"
echo "wrote $out ($(grep -c '^kind: KafkaTopic' "$out") topics)"
